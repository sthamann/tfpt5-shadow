# --- exact JW Majorana engine (pure states; NEVER calls the Pfaffian)
_I_POW = (1 + 0j, 1j, -1 + 0j, -1j)


def jw_moment_factory(nsites):
    """Return moment(idxs): the exact vacuum expectation
    <0| gamma_{i1} ... gamma_{ik} |0> on nsites JW sites.
    Values are always in {0, +-1, +-i}; phase tracked as an integer
    exponent of i (exact)."""
    def moment(idxs):
        state = 0
        e = 0  # phase = i**e
        for a in reversed(idxs):
            site, kind = a >> 1, a & 1
            below = state & ((1 << site) - 1)
            e += 2 * bin(below).count("1")  # Z string: (-1)^m = i^{2m}
            bit = (state >> site) & 1
            if kind == 1:                    # Y: |0>->i|1>, |1>->-i|0>
                e += 3 if bit else 1
            state ^= (1 << site)
        return _I_POW[e & 3] if state == 0 else 0j
    return moment


def pf(mat):
    """Pfaffian by first-row expansion; generic complex; exact for
    Gaussian-integer input (small sums, integer round-trip holds)."""
    n = len(mat)
    if n % 2 == 1:
        return 0j
    if n == 0:
        return 1 + 0j
    if n == 2:
        return mat[0][1]
    total = 0j
    rest0 = list(range(1, n))
    for j, col in enumerate(rest0):
        w = mat[0][col]
        if w == 0:
            continue
        keep = [r for r in rest0 if r != col]
        sub = [[mat[p][q] for q in keep] for p in keep]
        total += ((-1) ** j) * w * pf(sub)
    return total


def wick_pf(K, idxs):
    sub = [[K[a][b] for b in idxs] for a in idxs]
    return pf(sub)


def gi(z, tol=1e-9):
    """Assert z is (numerically exactly) a Gaussian integer; return it."""
    zr, zi = round(z.real), round(z.imag)
    assert abs(z.real - zr) < tol and abs(z.imag - zi) < tol
    return complex(zr, zi)


# --- exact Clifford monomial engine (subsets as bitmasks)
def cliff_sign(s_mask, t_mask, n):
    """eps(S,T) with gamma_S gamma_T = eps gamma_{S xor T}:
    (-1)^{#{(s,t) in S x T : s > t}}."""
    inv = 0
    for s in range(n):
        if (s_mask >> s) & 1:
            inv += bin(t_mask & ((1 << s) - 1)).count("1")
    return -1 if (inv & 1) else 1


def bfs_closure(n, gen_masks):
    """Monomial closure of span{gamma_m : m in gen_masks + {0}} under
    multiplication; returns (reached_set, level_sizes)."""
    reached = {0} | set(gen_masks)
    levels = [len(reached)]
    frontier = set(reached)
    while True:
        new = set()
        for m in frontier:
            for g in gen_masks:
                p = m ^ g
                if p not in reached:
                    new.add(p)
        if not new:
            break
        reached |= new
        levels.append(len(reached))
        frontier = new
    return reached, levels


# --- exact exterior monomial engine
def wedge_sign(s_mask, t_mask):
    """e_S wedge e_T = sign * e_{S|T} (0 if overlap); indices
    ascending inside each monomial."""
    if s_mask & t_mask:
        return 0
    inv = 0
    m = s_mask
    while m:
        s = (m & -m).bit_length() - 1
        inv += bin(t_mask & ((1 << s) - 1)).count("1")
        m &= m - 1
    return -1 if (inv & 1) else 1


def duads(g):
    return [(1 << a) | (1 << b)
            for a in range(g) for b in range(a + 1, g)]


def perfect_matchings(verts):
    verts = sorted(verts)
    if not verts:
        return [[]]
    out = []
    v0 = verts[0]
    for w in verts[1:]:
        rest = [x for x in verts[1:] if x != w]
        for m in perfect_matchings(rest):
            out.append([(v0, w)] + m)
    return out


def dfact(k):
    """double factorial, (-1)!! = 0!! = 1."""
    r = 1
    while k > 1:
        r *= k
        k -= 2
    return r


