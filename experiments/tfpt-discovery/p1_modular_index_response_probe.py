def jw_ops(n):
    sm = np.array([[0, 1], [0, 0]], dtype=complex)
    sz = np.array([[1, 0], [0, -1]], dtype=complex)
    I2c = np.eye(2, dtype=complex)
    ops = []
    for j in range(n):
        m = np.array([[1.0]], dtype=complex)
        for l in range(n):
            m = np.kron(m, sz if l < j else (sm if l == j else I2c))
        ops.append(m)
    return ops


def majoranas(n_modes):
    cs = jw_ops(n_modes)
    gs = []
    for p in range(n_modes):
        gs.append(cs[p] + cs[p].conj().T)              # gamma_{2p}
        gs.append(1j * (cs[p] - cs[p].conj().T))       # gamma_{2p+1}
    return gs, cs


def quad_op(h, gs):
    """Fock lift H(h) = -(i/4) sum h_ij gamma_i gamma_j (frozen sign:
    reproduces the sibling kms_A covariance -- ward S0.3)."""
    n = h.shape[0]
    dim = gs[0].shape[0]
    H = np.zeros((dim, dim), dtype=complex)
    for i in range(n):
        for j in range(n):
            if h[i, j] != 0.0:
                H += (-0.25j) * h[i, j] * (gs[i] @ gs[j])
    return (H + H.conj().T) / 2


def kms_A(h, beta):
    """sibling convention (kms_A_gen): complex covariance C and the
    antisymmetric two-point kernel A with omega(c_a c_b) = delta + iA."""
    n = h.shape[0]
    w, Q = np.linalg.eigh(1j * h)
    f = 1.0 / (1.0 + np.exp(np.clip(beta * w, -700, 700)))
    C = (Q * f) @ Q.conj().T
    return np.real(-1j * (2 * C - np.eye(n))), C


def gibbs(H, beta):
    w, V = np.linalg.eigh(H)
    lw = -beta * w
    lw -= lw.max()
    p = np.exp(lw)
    p /= p.sum()
    return (V * p) @ V.conj().T, w, V, p


def vn_entropy(rho):
    lam = np.linalg.eigvalsh(rho)
    lam = lam[lam > 1e-300]
    return float(-(lam * np.log(lam)).sum())


def rel_entropy(rho, sigma):
    lr, Vr = np.linalg.eigh(rho)
    ls, Vs = np.linalg.eigh(sigma)
    lr = np.clip(lr, 1e-300, None)
    ls = np.clip(ls, 1e-300, None)
    t1 = float((lr * np.log(lr)).sum())
    logs = (Vs * np.log(ls)) @ Vs.conj().T
    t2 = float(np.real(np.trace(rho @ logs)))
    return t1 - t2


def kln(p, q):
    """logarithmic mean k(p, q) = (p - q)/(log p - log q), k(p,p) = p."""
    if p <= 0.0 and q <= 0.0:
        return 0.0
    if abs(p - q) < 1e-14 * max(p, q):
        return 0.5 * (p + q)
    return (p - q) / (math.log(p) - math.log(q))


