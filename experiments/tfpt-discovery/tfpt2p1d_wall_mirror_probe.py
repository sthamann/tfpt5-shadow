SX = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=complex)
SY = np.array([[0.0, -1j], [1j, 0.0]], dtype=complex)
SZ = np.diag([1.0, -1.0]).astype(complex)
TY = SY / (2j) - SZ / 2.0

CHECKS: list[tuple[str, bool, str]] = []


def check(name: str, passed: bool, detail: str) -> bool:
    result = bool(passed)
    CHECKS.append((name, result, detail))
    print("  [%s] %-39s %s" % ("PASS" if result else "FAIL", name, detail))
    return result


def verify_freeze() -> str:
    if __doc__ is None:
        raise AssertionError("module docstring required")
    doc_payload = (
        __doc__.split("PREREGISTRATION_FREEZE_BEGIN", 1)[1]
        .split("PREREGISTRATION_FREEZE_END", 1)[0]
        .strip()
    )
    runtime_payload = "\n".join(
        (
            "model=QWZ_open_y_strip_x_four_flavor_edge_Fock",
            "geometry=Lx%d_periodic_x_Ly%d_open_y" % (LX, LY),
            "wall=QWZ_M1_physical_y0_mirror_y7",
            "edge_cluster=%d_modes_per_edge_per_k_Fock_dim%d"
            % (FLAVORS, 1 << FLAVORS),
            "combined_edge_Fock_dim=%d" % (1 << (2 * FLAVORS)),
            "mirror_vertex=lambda_det*(1-P_phi)_mirror_only",
            "P_phi=(|0>+exp(i*phi)|1111>)(h.c.)/2",
            "lambda_det=%s" % DET_STRENGTH,
            "phi=pi/7",
            "hopping_t=" + ",".join(str(value) for value in HOPPING_VALUES),
            "momentum_grid=129_points_minus_pi_to_pi",
            "edge_gap=min_single_fermion_add_remove_spectral_cost_over_k",
            "physical_crossing=QWZ_bottom_branch_signed_zero_crossing",
            "symmetry=global_Z4_charge_and_fermion_parity",
            "T7=physical_edge_four_density_cumulant_beta0.7_U0.4",
            "mutants=remove_DET;apply_DET_to_physical",
            "scope=no_dynamical_links_no_full_Spin10",
        )
    )
    declared = __doc__.split("PREREGISTRATION_SHA256=", 1)[1].split()[0]
    payloads = (doc_payload, FROZEN_DEFINITION, runtime_payload)
    if len(set(payloads)) != 1:
        raise AssertionError("frozen payloads differ")
    digest = hashlib.sha256(doc_payload.encode("utf-8")).hexdigest()
    if digest != declared or declared != FROZEN_SHA256:
        raise AssertionError("frozen SHA256 mismatch")
    return digest


def qwz_strip(momentum: float, hopping: float = 1.0) -> np.ndarray:
    """Chern-one QWZ strip, Bloch x and open y."""
    onsite = (
        hopping * math.sin(momentum) * SX
        + (MASS - hopping * math.cos(momentum)) * SZ
    )
    transverse = hopping * TY
    matrix = np.zeros((2 * LY, 2 * LY), dtype=complex)
    for y in range(LY):
        site = slice(2 * y, 2 * y + 2)
        matrix[site, site] = onsite
    for y in range(LY - 1):
        lower = slice(2 * y, 2 * y + 2)
        upper = slice(2 * (y + 1), 2 * (y + 1) + 2)
        matrix[upper, lower] = transverse
        matrix[lower, upper] = transverse.conj().T
    return matrix


def localized_zero_profiles() -> tuple[np.ndarray, np.ndarray, float]:
    """Diagonalize y inside the two-dimensional k=0 zero-mode subspace."""
    eigenvalues, eigenvectors = np.linalg.eigh(qwz_strip(0.0))
    zero_indices = np.where(np.abs(eigenvalues) < 1.0e-10)[0]
    if len(zero_indices) != 2:
        raise RuntimeError("QWZ strip did not have exactly two zero modes")
    zero_frame = eigenvectors[:, zero_indices]
    y_operator = np.diag(np.repeat(np.arange(LY, dtype=float), 2))
    y_restricted = zero_frame.conj().T @ y_operator @ zero_frame
    positions, rotation = np.linalg.eigh(y_restricted)
    localized = zero_frame @ rotation
    physical = localized[:, 0]
    mirror = localized[:, 1]
    return physical, mirror, float(abs(np.vdot(physical, mirror)))


def edge_branch(momentum: float, edge: str) -> tuple[float, float]:
    """Energy and boundary-row weight of the most localized in-gap state."""
    eigenvalues, eigenvectors = np.linalg.eigh(qwz_strip(momentum))
    candidates = np.where(np.abs(eigenvalues) < 0.9)[0]
    if not len(candidates):
        raise RuntimeError("no QWZ in-gap edge candidate")
    boundary = slice(0, 2) if edge == "physical" else slice(-2, None)
    weights = [
        float(np.sum(np.abs(eigenvectors[boundary, index]) ** 2))
        for index in candidates
    ]
    selected = int(candidates[int(np.argmax(weights))])
    return float(eigenvalues[selected]), max(weights)


def jw_annihilator(mode: int) -> np.ndarray:
    dimension = 1 << FLAVORS
    matrix = np.zeros((dimension, dimension), dtype=complex)
    for state in range(dimension):
        if state & (1 << mode):
            target = state ^ (1 << mode)
            sign = -1 if (
                state & ((1 << mode) - 1)
            ).bit_count() % 2 else 1
            matrix[target, state] = sign
    return matrix


ANNIHILATORS = tuple(jw_annihilator(mode) for mode in range(FLAVORS))
NUMBER = sum(operator.conj().T @ operator for operator in ANNIHILATORS)
PARITY = np.diag(
    [(-1.0) ** state.bit_count() for state in range(1 << FLAVORS)]
).astype(complex)
Z4_CHARGE = np.diag(
    [(1j) ** state.bit_count() for state in range(1 << FLAVORS)]
).astype(complex)


def determinant_projector() -> np.ndarray:
    omega = np.zeros(1 << FLAVORS, dtype=complex)
    omega[0] = 1.0 / math.sqrt(2.0)
    omega[-1] = np.exp(1j * DET_PHASE) / math.sqrt(2.0)
    return np.outer(omega, omega.conj())


P_PHI = determinant_projector()
H_DET = np.eye(1 << FLAVORS, dtype=complex) - P_PHI


def edge_cluster_hamiltonian(
    dispersion: float,
    det_enabled: bool,
) -> np.ndarray:
    matrix = dispersion * (NUMBER - 0.5 * FLAVORS * np.eye(1 << FLAVORS))
    if det_enabled:
        matrix = matrix + DET_STRENGTH * H_DET
    return matrix


@dataclass(frozen=True)
class SpectralThreshold:
    gap: float
    zero_weight: float


def cluster_spectral_threshold(matrix: np.ndarray) -> SpectralThreshold:
    """Lowest c/cdag spectral support from the possibly degenerate ground space."""
    eigenvalues, eigenvectors = np.linalg.eigh(matrix)
    ground_energy = float(eigenvalues[0])
    ground_indices = np.where(
        np.abs(eigenvalues - ground_energy) < 1.0e-10
    )[0]
    minimum = math.inf
    zero_weight = 0.0
    for ground_index in ground_indices:
        ground = eigenvectors[:, ground_index]
        for annihilator in ANNIHILATORS:
            for field in (annihilator, annihilator.conj().T):
                amplitudes = eigenvectors.conj().T @ (field @ ground)
                weights = np.abs(amplitudes) ** 2
                supported = np.where(weights > 1.0e-12)[0]
                for target in supported:
                    cost = float(eigenvalues[target] - ground_energy)
                    if cost >= -1.0e-10:
                        minimum = min(minimum, max(0.0, cost))
                        if abs(cost) < EDGE_GAP_TOL:
                            zero_weight += float(weights[target])
    if not math.isfinite(minimum):
        raise RuntimeError("edge spectral function had no support")
    return SpectralThreshold(minimum, zero_weight)


def edge_spectral_scan(
    hopping: float,
    det_enabled: bool,
    chirality_sign: int,
) -> SpectralThreshold:
    minimum_gap = math.inf
    zero_weight = 0.0
    for momentum in MOMENTA:
        dispersion = chirality_sign * hopping * math.sin(float(momentum))
        threshold = cluster_spectral_threshold(
            edge_cluster_hamiltonian(dispersion, det_enabled)
        )
        minimum_gap = min(minimum_gap, threshold.gap)
        if threshold.gap < EDGE_GAP_TOL:
            zero_weight = max(zero_weight, threshold.zero_weight)
    return SpectralThreshold(minimum_gap, zero_weight)


def combined_symmetry_errors(hopping: float) -> tuple[float, float]:
    """Mirror-gapped edge pair at one generic momentum, Fock dim 256."""
    momentum = 0.37
    physical = edge_cluster_hamiltonian(
        +hopping * math.sin(momentum), False
    )
    mirror = edge_cluster_hamiltonian(
        -hopping * math.sin(momentum), True
    )
    identity = np.eye(1 << FLAVORS, dtype=complex)
    combined = np.kron(physical, identity) + np.kron(identity, mirror)
    charge = np.kron(Z4_CHARGE, Z4_CHARGE)
    parity = np.kron(PARITY, PARITY)
    return (
        float(np.max(np.abs(combined @ charge - charge @ combined))),
        float(np.max(np.abs(combined @ parity - parity @ combined))),
    )


def fourth_density_cumulant(interaction: float) -> float:
    """Thermal connected cumulant of four distinct physical-edge densities."""
    states = np.arange(1 << FLAVORS, dtype=np.int64)
    centered = np.array(
        [
            [((state >> mode) & 1) - 0.5 for mode in range(FLAVORS)]
            for state in states
        ],
        dtype=float,
    )
    energies = interaction * np.sum(
        centered * np.roll(centered, -1, axis=1), axis=1
    )
    weights = np.exp(-INTERACTION_BETA * energies)
    weights /= np.sum(weights)

    def expectation(indices: tuple[int, ...]) -> float:
        return float(np.dot(weights, np.prod(centered[:, indices], axis=1)))

    fourth = expectation((0, 1, 2, 3))
    pairings = (
        expectation((0, 1)) * expectation((2, 3))
        + expectation((0, 2)) * expectation((1, 3))
        + expectation((0, 3)) * expectation((1, 2))
    )
    return fourth - pairings


