    passed = sum(result for _, result, _ in CHECKS)
    total = len(CHECKS)
    all_pass = passed == total
    verdict = (
        "WALL_MIRROR_INTEGRATED("
        "physical_gap=0,mirror_gap_min=%.6f,edge_contrast=PASS)"
        % min(integrated_mirror_gaps)
        if all_pass
        else "WALL_MIRROR_BLOCKED(%d_failed)" % (total - passed)
    )
    print("\n" + "=" * 94)
    print("RESULT: %d/%d CHECKS PASS" % (passed, total))
    print("VERDICT: %s" % verdict)
    print("QFT4D contracts stay [O]")
    print("=" * 94)
    return 0 if all_pass else 1


