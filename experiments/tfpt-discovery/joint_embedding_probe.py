import sympy as sp
from sympy.matrices.normalforms import smith_normal_form

t = sp.symbols("t")
x = sp.symbols("x")
OMEGA = sp.Rational(-1, 2) + sp.sqrt(3) * sp.I / 2

CHECKS = []


def check(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    print("[%s] %s%s" % ("PASS" if ok else "FAIL", name, (" -- " + detail) if detail else ""))


def burau_gen(i, n=4):
    m = n - 1
    M = sp.eye(m)
    if i - 2 >= 0:
        M[i - 2, i - 1] = t
    M[i - 1, i - 1] = -t
    if i < m:
        M[i, i - 1] = 1
    return M


I3 = sp.eye(3)
S = [sp.simplify(burau_gen(i).subs({t: OMEGA})) for i in (1, 2, 3)]
r = sp.simplify(S[0] * S[1] * S[2])
T = [S[0]]
for _ in range(3):
    T.append(sp.simplify(r * T[-1] * r.inv()))
G = [sp.simplify((I3 - T[k]) * (I3 - T[k]).conjugate().T) for k in range(4)]

M = sp.Matrix([[-1, (1 + sp.sqrt(3) * sp.I) / 2, (1 - sp.sqrt(3) * sp.I) / 2],
               [0, 0, 1],
               [0, 1, 0]])
Minv = M.inv()


def Gamma(A):
    return sp.simplify(M * A.conjugate() * Minv)


def charpoly(A):
    return sp.factor(sp.simplify(sp.expand((x * I3 - A).det())))


def zw_coords(e):
    """Entry of Q(omega) as a + b*omega with rational a, b."""
    e = sp.expand(e)
    b = sp.nsimplify(2 * sp.im(e) / sp.sqrt(3))
    a = sp.nsimplify(sp.re(e) + sp.im(e) / sp.sqrt(3))
    return a, b


# ---------------------------------------------------------------- the pair
E1 = sp.simplify(G[0] + Gamma(G[0]))
E3 = sp.simplify(G[2] + Gamma(G[2]))
sym11 = sp.simplify(G[0] * Gamma(G[0]) + Gamma(G[0]) * G[0])
sym22 = sp.simplify(G[1] * Gamma(G[1]) + Gamma(G[1]) * G[1])
Ustar = sp.simplify(-2 * E1 + sym11 + 3 * I3)
Vstar = sp.simplify(-E3 + sp.Rational(1, 2) * sym22 + I3)

Uc = sp.Matrix([[3, 0, 0], [3, 0, 0], [3, 0, 0]])
Vc = sp.Matrix([[0, 1, 0], [0, 2, 0], [0, 2, 1]])

# ---------------------------------------------------------------- J1
