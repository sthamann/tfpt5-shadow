def charpoly_float(K: np.ndarray) -> tuple[tuple[int, ...], float]:
    """Rounded charpoly of M = K/2; return (coeffs desc, max round residual)."""
    p = np.poly(K.astype(np.float64) * 0.5)
    pr = np.rint(p)
    err = float(np.max(np.abs(p - pr)))
    return tuple(int(c) for c in pr), err


def exact_charpoly(K: np.ndarray, xsym) -> tuple[int, ...]:
    M = sp.Matrix(K.tolist()) / 2
    coeffs = sp.Poly(M.charpoly(xsym).as_expr(), xsym).all_coeffs()
    return tuple(int(c) for c in coeffs)


def cluster_values(arr: np.ndarray, tol: float = TOL) -> list[tuple[float, int]]:
    s = np.sort(arr)
    groups: list[list[float]] = []
    for v in s:
        if not groups or abs(v - groups[-1][0]) > tol:
            groups.append([float(v), 1.0])
        else:
            n = groups[-1][1]
            groups[-1][0] = (groups[-1][0] * n + float(v)) / (n + 1.0)
            groups[-1][1] = n + 1.0
    return [(g[0], int(g[1])) for g in groups]


def match_root_sets(got: list[complex], targets: list[complex], tol: float) -> bool:
    unused = list(targets)
    for z in got:
        best_i = None
        best_d = 1e9
        for i, t in enumerate(unused):
            d = abs(z - t)
            if d < best_d:
                best_d = d
                best_i = i
        if best_i is None or best_d > tol:
            return False
        unused.pop(best_i)
    return not unused


def dynkin_is_e8(cartan: np.ndarray) -> bool:
    if cartan.shape != (8, 8):
        return False
    if not np.array_equal(np.diag(cartan), np.full(8, 2)):
        return False
    off = cartan.copy()
    np.fill_diagonal(off, 0)
    if not np.array_equal(off, off.T):
        return False
    if np.any((off != 0) & (off != -1)):
        return False
    adj = (off == -1).astype(int)
    n_edges = int(np.sum(adj) // 2)
    if n_edges != 7:
        return False
    deg = adj.sum(axis=1)
    if int(np.max(deg)) != 3 or int(np.sum(deg == 3)) != 1:
        return False
    c = int(np.argmax(deg))
    seen = {c}
    arm_lens = []
    for nb in np.where(adj[c] == 1)[0]:
        length = 1
        prev, cur = c, int(nb)
        seen.add(cur)
        while True:
            nxts = [int(j) for j in np.where(adj[cur] == 1)[0] if j != prev]
            if not nxts:
                break
            if len(nxts) != 1:
                return False
            prev, cur = cur, nxts[0]
            seen.add(cur)
            length += 1
        arm_lens.append(length)
    return sorted(arm_lens) == [1, 2, 4] and len(seen) == 8


