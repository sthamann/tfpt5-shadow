def permute_word(c: tuple[int, ...], p: tuple[int, ...] | list[int] | np.ndarray) -> tuple[int, ...]:
    out = [0] * 8
    for i in range(8):
        out[int(p[i])] = c[i]
    return tuple(out)


def build_code() -> tuple[tuple[int, ...], ...]:
    words: set[tuple[int, ...]] = set()
    words.add((0,) * 8)
    words.add((1,) * 8)
    pair_unions = (
        (0, 1, 2, 3),
        (0, 1, 4, 5),
        (2, 3, 4, 5),
        (0, 1, 6, 7),
        (2, 3, 6, 7),
        (4, 5, 6, 7),
    )
    for s in pair_unions:
        w = [0] * 8
        for i in s:
            w[i] = 1
        words.add(tuple(w))
    for d in itertools.product((0, 1), repeat=4):
        if sum(d) % 2 == 0:
            w = [0] * 8
            for k in range(4):
                w[2 * k + d[k]] = 1
            words.add(tuple(w))
    return tuple(sorted(words))


def build_roots(code: tuple[tuple[int, ...], ...]) -> np.ndarray:
    roots: list[tuple[int, ...]] = []
    for i in range(8):
        for s in (2, -2):
            v = [0] * 8
            v[i] = s
            roots.append(tuple(v))
    for c in code:
        if sum(c) != 4:
            continue
        supp = [i for i, b in enumerate(c) if b]
        for signs in itertools.product((-1, 1), repeat=4):
            v = [0] * 8
            for idx, si in zip(supp, signs):
                v[idx] = si
            roots.append(tuple(v))
    uniq = sorted(set(roots))
    return np.array(uniq, dtype=np.int64)


def j_mat() -> np.ndarray:
    jm = np.zeros((8, 8), dtype=np.int64)
    for k in range(4):
        jm[2 * k + 1, 2 * k] = 1
        jm[2 * k, 2 * k + 1] = -1
    return jm


def sigma_mat() -> np.ndarray:
    sm = np.zeros((8, 8), dtype=np.int64)
    sm[2, 0] = 1
    sm[4, 2] = 1
    sm[0, 4] = 1
    sm[3, 1] = 1
    sm[5, 3] = 1
    sm[1, 5] = 1
    sm[6, 6] = 1
    sm[7, 7] = 1
    return sm


def apply_mat_rows(rd: np.ndarray, m: np.ndarray) -> np.ndarray:
    return rd @ m.T


def perm_from_images(rd: np.ndarray, images: np.ndarray, ridx: dict) -> np.ndarray:
    return np.array(
        [ridx[tuple(int(t) for t in images[i])] for i in range(len(rd))],
        dtype=np.int16,
    )


def reflect_all(rd: np.ndarray, a: np.ndarray) -> np.ndarray:
    ip = rd @ a
    return rd - (ip[:, None] // 2) * a[None, :]


def j2_block(k: int) -> np.ndarray:
    blocks = (
        np.array([[1, 0], [0, 1]], dtype=np.int64),
        np.array([[0, -1], [1, 0]], dtype=np.int64),
        np.array([[-1, 0], [0, -1]], dtype=np.int64),
        np.array([[0, 1], [-1, 0]], dtype=np.int64),
    )
    return blocks[k]


def wreath_matrix(p: tuple[int, ...], ks: tuple[int, ...]) -> np.ndarray:
    """Pair i --p--> pair p[i], then J^{ks[i]} on the target pair.

    g e_{2i}     = J_pair^{ks[i]} e_{2 p[i]}
    g e_{2i+1}   = J_pair^{ks[i]} e_{2 p[i]+1}
    """
    g = np.zeros((8, 8), dtype=np.int64)
    for i in range(4):
        dest = p[i]
        blk = j2_block(ks[i])
        g[2 * dest, 2 * i] = blk[0, 0]
        g[2 * dest + 1, 2 * i] = blk[1, 0]
        g[2 * dest, 2 * i + 1] = blk[0, 1]
        g[2 * dest + 1, 2 * i + 1] = blk[1, 1]
    return g


def induced_coord_perm(g: np.ndarray) -> tuple[int, ...]:
    p = [0] * 8
    for i in range(8):
        col = g[:, i]
        nz = np.flatnonzero(col)
        p[i] = int(nz[0])
    return tuple(p)


def bfs_group(gens: list[np.ndarray], cap: int = 50000):
    ident = np.arange(N240, dtype=np.int16)
    seen = {ident.tobytes(): ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for p in frontier:
            for gen in gens:
                q = p[gen]
                b = q.tobytes()
                if b not in seen:
                    seen[b] = q
                    nxt.append(q)
                    if len(seen) > cap:
                        return seen, False
        frontier = nxt
    return seen, True


def orbit_sizes(words: tuple[tuple[int, ...], ...], p: tuple[int, ...]) -> list[int]:
    remaining = set(words)
    sizes = []
    while remaining:
        seed = remaining.pop()
        orb = {seed}
        cur = seed
        while True:
            cur = permute_word(cur, p)
            if cur in orb:
                break
            orb.add(cur)
        remaining -= orb
        sizes.append(len(orb))
    sizes.sort()
    return sizes


